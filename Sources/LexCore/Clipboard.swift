import CryptoKit
import Foundation

/// Everything one copy put on the clipboard: each pasteboard item's data by type, so pasting
/// it back keeps its formatting (rich text, links, images, files).
public typealias ClipData = [[String: Data]]

/// One entry in the clipboard history. The full data lives in its own file; this is what the
/// list shows and searches.
public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable { case text, link, image, files }

    public let id: UUID
    public var date: Date
    public var kind: Kind
    /// Plain text, a link, or file names: what the row shows and search reads (capped).
    public var text: String
    public var appID: String?
    public var appName: String?
    public var pinned: Bool
    public var bytes: Int
    /// Identical copies share it, so copying the same thing again moves it to the top.
    public var fingerprint: String
}

public enum ClipTypes {
    public static let plainText = "public.utf8-plain-text"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
}

public enum ClipPolicy {
    /// Types apps add to say "don't keep this" (nspasteboard.org): passwords, one-time codes,
    /// and text another tool put there for a moment (Lex's own pastes among them).
    public static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]

    /// Password managers: nothing copied while they're in front is kept.
    public static let defaultIgnoredApps = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.apple.Passwords", "com.apple.keychainaccess",
        "com.bitwarden.desktop", "com.dashlane.dashlanephonefinal", "com.lastpass.LastPass", "org.keepassxc.keepassxc",
    ]

    /// Bigger copies (huge screenshots, whole documents) aren't kept.
    public static let maxBytes = 20 * 1024 * 1024

    public static func shouldRecord(types: [String], appID: String?, ignoredApps: [String]) -> Bool {
        guard !types.isEmpty else { return false }
        if types.contains(where: privateMarkers.contains) { return false }
        if let appID, ignoredApps.contains(appID) { return false }
        return true
    }

    /// Types worth keeping: not dynamic aliases (duplicates of real types) or file promises
    /// (reading those makes the source app write files).
    public static func keeps(_ type: String) -> Bool {
        !type.hasPrefix("dyn.") && !type.lowercased().contains("promise")
    }

    /// What a copy is, and the text the list shows for it. Nil when there's nothing to show.
    public static func describe(_ data: ClipData) -> (kind: ClipItem.Kind, text: String)? {
        let files = data.compactMap { $0[ClipTypes.fileURL] }
            .compactMap { String(data: $0, encoding: .utf8) }
            .compactMap { URL(string: $0) }
            .filter(\.isFileURL)
        if !files.isEmpty { return (.files, files.map(\.path).joined(separator: "\n")) }
        if let text = data.first?[ClipTypes.plainText].flatMap({ String(data: $0, encoding: .utf8) }),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(where: \.isWhitespace) && ["http", "https"].contains(URL(string: trimmed)?.scheme?.lowercased() ?? "")
            return (isLink ? .link : .text, text)
        }
        if data.contains(where: { $0[ClipTypes.png] != nil || $0[ClipTypes.tiff] != nil }) { return (.image, "") }
        return nil
    }

    static func fingerprint(_ kind: ClipItem.Kind, text: String, data: ClipData) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(kind.rawValue.utf8))
        if kind == .image {
            for item in data { if let image = item[ClipTypes.png] ?? item[ClipTypes.tiff] { hasher.update(data: image) } }
        } else {
            hasher.update(data: Data(text.utf8))
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

/// Where a clipboard history is kept: an index and one item per entry, by name.
public protocol ClipboardStorage {
    func read(_ name: String) -> Data?
    func write(_ data: Data, as name: String)
    func remove(_ name: String)
    /// Every name saved, so entries whose data is gone can be left out.
    func names() -> Set<String>
}

/// A folder on disk, readable only by you.
public struct FolderStorage: ClipboardStorage {
    public let directory: URL

    public init(_ directory: URL) { self.directory = directory }

    public func read(_ name: String) -> Data? { try? Data(contentsOf: directory.appendingPathComponent(name)) }

    public func write(_ data: Data, as name: String) {
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        try? data.write(to: directory.appendingPathComponent(name), options: .atomic)
    }

    public func remove(_ name: String) { try? FileManager.default.removeItem(at: directory.appendingPathComponent(name)) }

    public func names() -> Set<String> { Set((try? FileManager.default.contentsOfDirectory(atPath: directory.path)) ?? []) }
}

/// The clipboard history, newest first: an index plus one saved item per entry.
public final class ClipboardStore {
    public private(set) var items: [ClipItem] = []
    /// How long unpinned entries are kept.
    public var retention: TimeInterval
    public var maxItems: Int
    /// Bigger copies aren't kept.
    public var maxBytes: Int
    /// Text kept in the index for the list and search; the full text is in the entry's file.
    public static let indexTextLimit = 2000

    private let storage: ClipboardStorage?

    public convenience init(directory: URL?, retention: TimeInterval = 30 * 86400, maxItems: Int = 1000) {
        self.init(storage: directory.map(FolderStorage.init), retention: retention, maxItems: maxItems)
    }

    public init(storage: ClipboardStorage?, retention: TimeInterval = 30 * 86400, maxItems: Int = 1000, maxBytes: Int = ClipPolicy.maxBytes) {
        self.storage = storage
        self.retention = retention
        self.maxItems = maxItems
        self.maxBytes = maxBytes
    }

    // MARK: Reading

    /// Pinned entries first, then newest first.
    public var ordered: [ClipItem] { items.filter(\.pinned) + items.filter { !$0.pinned } }

    /// Entries whose text or app has every word of `query`, case- and accent-insensitive.
    public static func search(_ items: [ClipItem], _ query: String) -> [ClipItem] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        guard !words.isEmpty else { return items }
        return items.filter { item in
            let haystack = item.text + " " + (item.appName ?? "")
            return words.allSatisfy { haystack.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
    }

    public func data(for id: UUID) -> ClipData? {
        guard let raw = storage?.read(Self.blobName(id)) else { return nil }
        return try? PropertyListDecoder().decode(ClipData.self, from: raw)
    }

    /// The whole text of an entry (the index keeps only the start of long ones).
    public func fullText(for item: ClipItem) -> String {
        guard item.kind == .text || item.kind == .link, item.text.count >= Self.indexTextLimit,
              let text = data(for: item.id)?.first?[ClipTypes.plainText].flatMap({ String(data: $0, encoding: .utf8) }) else { return item.text }
        return text
    }

    // MARK: Changing

    /// Adds a copy. The same content again moves its entry to the top instead of duplicating it.
    @discardableResult
    public func add(_ data: ClipData, appID: String?, appName: String?, date: Date = Date()) -> ClipItem? {
        let bytes = data.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
        guard bytes <= maxBytes, let (kind, text) = ClipPolicy.describe(data) else { return nil }
        let fingerprint = ClipPolicy.fingerprint(kind, text: text, data: data)
        if let i = items.firstIndex(where: { $0.fingerprint == fingerprint }) {
            var existing = items.remove(at: i)
            existing.date = date
            existing.appID = appID ?? existing.appID
            existing.appName = appName ?? existing.appName
            items.insert(existing, at: 0)
            saveIndex()
            return existing
        }
        let item = ClipItem(id: UUID(), date: date, kind: kind, text: String(text.prefix(Self.indexTextLimit)),
                            appID: appID, appName: appName, pinned: false, bytes: bytes, fingerprint: fingerprint)
        if let storage, let encoded = try? PropertyListEncoder().encode(data) { storage.write(encoded, as: Self.blobName(item.id)) }
        items.insert(item, at: 0)
        prune(now: date)
        saveIndex()
        return item
    }

    public func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        saveIndex()
    }

    public func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
        storage?.remove(Self.blobName(id))
        saveIndex()
    }

    /// Removes everything except pinned entries.
    public func clear() {
        for item in items where !item.pinned { storage?.remove(Self.blobName(item.id)) }
        items.removeAll { !$0.pinned }
        saveIndex()
    }

    /// Drops unpinned entries older than the retention, and the oldest past `maxItems`.
    public func prune(now: Date = Date()) {
        var kept: [ClipItem] = []
        var unpinned = 0
        for item in items {
            let keep = item.pinned || (now.timeIntervalSince(item.date) <= retention && unpinned < maxItems)
            if keep {
                kept.append(item)
                if !item.pinned { unpinned += 1 }
            } else {
                storage?.remove(Self.blobName(item.id))
            }
        }
        if kept.count != items.count {
            items = kept
            saveIndex()
        }
    }

    // MARK: Saving

    public func load() {
        guard let storage, let raw = storage.read("index.json"),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: raw) else { return }
        // An entry whose data is gone can't be pasted; leave it out.
        let saved = storage.names()
        items = decoded.filter { saved.contains(Self.blobName($0.id)) }
        prune()
    }

    private func saveIndex() {
        guard let storage, let encoded = try? JSONEncoder().encode(items) else { return }
        storage.write(encoded, as: "index.json")
    }

    private static func blobName(_ id: UUID) -> String { "\(id.uuidString).plist" }
}
